#!/usr/bin/env bash
# Generates a local-only .env for compose.yaml. Every value is random and disposable.
# Usage: deploy/generate-local-secrets.sh [path-to-env-file]
set -euo pipefail

target="${1:-.env}"
umask 077

if [ -e "${target}" ]; then
  echo "refusing to overwrite existing ${target}" >&2
  exit 1
fi

random_credential() {
  openssl rand -base64 32 | tr -d '\n'
}

postgres_credential="$(random_credential)"
migrator_credential="$(random_credential)"
runtime_credential="$(random_credential)"
relay_credential="$(random_credential)"
reconciler_credential="$(random_credential)"
encryption_material="$(openssl rand -base64 32 | tr -d '\n')"
blind_index_material="$(openssl rand -base64 32 | tr -d '\n')"
challenge_digest_material="$(openssl rand -base64 32 | tr -d '\n')"
# prime256v1 through ecparam keeps the named-curve form Java's EC KeyFactory accepts.
signer_material="$(openssl ecparam -name prime256v1 -genkey -noout 2>/dev/null \
  | openssl pkcs8 -topk8 -nocrypt -outform DER \
  | base64 | tr -d '\n')"
workload_key_file="$(mktemp)"
trap 'rm -f "${workload_key_file}"' EXIT
openssl ecparam -name prime256v1 -genkey -noout -out "${workload_key_file}" 2>/dev/null
workload_private_material="$(openssl pkcs8 -topk8 -nocrypt -in "${workload_key_file}" -outform DER \
  | base64 | tr -d '\n')"
workload_public_material="$(openssl pkey -in "${workload_key_file}" -pubout -outform DER \
  | base64 | tr -d '\n')"

cat > "${target}" <<EOF
# Generated by deploy/generate-local-secrets.sh. Never commit this file.
POSTGRES_USER=postgres
POSTGRES_DB=iam
POSTGRES_PASSWORD=${postgres_credential}

IAM_MIGRATOR_PASSWORD=${migrator_credential}
IAM_RUNTIME_PASSWORD=${runtime_credential}
IAM_RELAY_PASSWORD=${relay_credential}
IAM_REGISTRATION_RECONCILER_PASSWORD=${reconciler_credential}

IAM_DB_URL=jdbc:postgresql://postgres:5432/iam
IAM_DB_USERNAME=iam_runtime
IAM_DB_PASSWORD=${runtime_credential}

IAM_FLYWAY_URL=jdbc:postgresql://postgres:5432/iam
IAM_FLYWAY_USERNAME=iam_migrator
IAM_FLYWAY_PASSWORD=${migrator_credential}

IAM_RECONCILER_URL=jdbc:postgresql://postgres:5432/iam
IAM_RECONCILER_USERNAME=iam_registration_reconciler
IAM_RECONCILER_PASSWORD=${reconciler_credential}

IAM_ISSUER=https://iam.example.test
IAM_REGISTRATION_ENABLED=true
IAM_FIXTURES_ENABLED=false
IAM_MESSAGING_ENABLED=true
IAM_RELAY_ENABLED=false

IAM_WORKLOAD_ENABLED=true
IAM_WORKLOAD_KEY_ID=local-workload-v1
IAM_WORKLOAD_SIGNING_PRIVATE_KEY=${workload_private_material}
IAM_WORKLOAD_SIGNING_PUBLIC_KEY=${workload_public_material}
IAM_WORKLOAD_ID=wl_localdevelopmentrelay01
IAM_WORKLOAD_APP_ID=dutch-development
IAM_WORKLOAD_CLIENT_ID=iam-relay
IAM_WORKLOAD_AUDIENCE=https://ums.example.test/internal/iam/events
IAM_WORKLOAD_SCOPE=ums:onboarding:write

IAM_CRYPTO_LOCAL_ENABLED=true
IAM_CRYPTO_LOCAL_PROVIDER=local-jca
IAM_CRYPTO_LOCAL_SIGNER_KEY_ID=local-signing-v1
IAM_CRYPTO_LOCAL_SIGNER_PRIVATE_KEY=${signer_material}
IAM_CRYPTO_LOCAL_ENCRYPTION_KEY_REFERENCE=local-encryption-v1
IAM_CRYPTO_LOCAL_ENCRYPTION_KEY=${encryption_material}
IAM_CRYPTO_LOCAL_BLIND_INDEX_KEY_REFERENCE=local-blind-index-v1
IAM_CRYPTO_LOCAL_BLIND_INDEX_KEY=${blind_index_material}
IAM_CRYPTO_LOCAL_CHALLENGE_DIGEST_KEY_REFERENCE=local-challenge-digest-v1
IAM_CRYPTO_LOCAL_CHALLENGE_DIGEST_KEY=${challenge_digest_material}
EOF

chmod 600 "${target}"
echo "wrote ${target}"
